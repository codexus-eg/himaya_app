// ─── Lightweight i18n for Himaya Track ───────────────────────────────────────
// Global, context-free translation helper.
//
// Usage:
//   tr('login')           → "تسجيل الدخول" / "Login"
//   tr('hello', {'n':'5'})→ supports {placeholder} substitution
//
// The current language is held in [I18n.lang] ('ar' | 'en') and is kept in sync
// with AppProvider.locale (set in loadLocale/setLocale). Because it's a plain
// global, it can be used from anywhere — including non-widget code — without a
// BuildContext. Widgets that need to rebuild on language change already do so
// via context.watch<AppProvider>() (which calls notifyListeners on setLocale).

class I18n {
  static String lang = 'ar';
  static bool get isAr => lang == 'ar';
  static bool get isEn => lang == 'en';
}

/// Translate [key] for the current language. Falls back to Arabic, then the key.
String tr(String key, [Map<String, String>? params]) {
  final table = _strings[key];
  String out;
  if (table == null) {
    out = key; // missing key → show the key (easy to spot during QA)
  } else {
    out = table[I18n.lang] ?? table['ar'] ?? key;
  }
  if (params != null) {
    params.forEach((k, v) => out = out.replaceAll('{$k}', v));
  }
  return out;
}

